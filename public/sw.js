/**
 * Intersect Service Worker (PWA Offline Runtime).
 *
 * Requirements (Section 10):
 * - Automatic background caching of the complete runtime closure on first visit.
 * - Cache-First for static assets, WASM, Python stdlib, SymPy wheel, and fonts.
 * - Same-origin and relative base-path compatibility.
 * - Network-First for document navigation with offline fallback so updates are instantly picked up.
 */

const CACHE_VERSION = 'v1.0.8';
const CACHE_NAME = `intersect-${CACHE_VERSION}`;

// Core shell assets always cached immediately
const CORE_SHELL_ASSETS = [
  './',
  './index.html',
  './manifest.webmanifest',
  './favicon.svg',
  './icon-192.png',
  './icon-512.png',
  './icon-maskable-192.png',
  './icon-maskable-512.png',
  './apple-touch-icon.png',
];

// Runtime files to be cached automatically in the background
const RUNTIME_ASSETS = [
  './pyodide/manifest.json',
  './pyodide/pyodide.asm.js',
  './pyodide/pyodide.asm.wasm',
  './pyodide/python_stdlib.zip',
  './pyodide/pyodide-lock.json',
  './pyodide/pyodide.mjs',
  './pyodide/mpmath-1.3.0-py3-none-any.whl',
  './pyodide/sympy-1.13.3-py3-none-any.whl',
];

self.addEventListener('install', (event) => {
  self.skipWaiting();
  event.waitUntil(
    caches.open(CACHE_NAME).then(async (cache) => {
      // Precache core shell files
      try {
        await cache.addAll(CORE_SHELL_ASSETS);
      } catch (err) {
        console.warn('Initial shell precache partial failure:', err);
      }
    }),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      await self.clients.claim();

      // Clean up all outdated caches immediately
      const keys = await caches.keys();
      await Promise.all(
        keys.map((key) => {
          if (key.startsWith('intersect-') && key !== CACHE_NAME) {
            console.log(`[SW] Evicting outdated cache: ${key}`);
            return caches.delete(key);
          }
        }),
      );

      // Start automatic background runtime preparation
      await prepareFullOfflineClosure();
    })(),
  );
});

self.addEventListener('message', (event) => {
  if (event.data?.type === 'PREPARE_OFFLINE') {
    event.waitUntil(prepareFullOfflineClosure());
  } else if (event.data?.type === 'SKIP_WAITING') {
    self.skipWaiting();
  }
});

/**
 * Prepares the entire runtime closure in the background with bounded concurrency.
 */
let offlinePreparation = null;

function prepareFullOfflineClosure() {
  if (!offlinePreparation) {
    offlinePreparation = cacheFullOfflineClosure().finally(() => {
      offlinePreparation = null;
    });
  }
  return offlinePreparation;
}

async function cacheFullOfflineClosure() {
  try {
    await notifyClients({ type: 'OFFLINE_PREPARING' });
    const cache = await caches.open(CACHE_NAME);

    // 1. Fetch cache-manifest if generated by build, or fallback to known runtime assets
    let dynamicAssets = [...RUNTIME_ASSETS];
    try {
      const manifestRes = await fetch('./cache-manifest.json');
      if (manifestRes.ok) {
        await cache.put('./cache-manifest.json', manifestRes.clone());
        const manifest = await manifestRes.json();
        if (Array.isArray(manifest.assets)) {
          dynamicAssets = manifest.assets;
        }
      }
    } catch {
      // Use built-in fallback list
    }

    // 2. Also ensure KaTeX fonts are included
    const fontNames = [
      'KaTeX_Main-Bold.woff2',
      'KaTeX_Main-Italic.woff2',
      'KaTeX_Main-Regular.woff2',
      'KaTeX_Math-BoldItalic.woff2',
      'KaTeX_Math-Italic.woff2',
      'KaTeX_Size1-Regular.woff2',
      'KaTeX_Size2-Regular.woff2',
      'KaTeX_Size3-Regular.woff2',
      'KaTeX_Size4-Regular.woff2',
      'KaTeX_Typewriter-Regular.woff2',
    ];
    for (const font of fontNames) {
      dynamicAssets.push(`./fonts/${font}`);
    }

    // Bounded concurrency pool (max 3 concurrent requests to avoid choking the thread)
    const queue = [...new Set(dynamicAssets)];
    const concurrency = 3;
    const failures = [];

    async function worker() {
      while (queue.length > 0) {
        const url = queue.shift();
        if (!url) break;

        const match = await cache.match(url);
        if (match) continue; // Already cached

        try {
          const res = await fetch(url);
          if (!res.ok) throw new Error(`HTTP ${res.status}`);
          await cache.put(url, res);
        } catch (err) {
          failures.push(url);
          console.warn(`Failed to precache ${url}:`, err);
        }
      }
    }

    const workers = [];
    for (let i = 0; i < concurrency; i++) {
      workers.push(worker());
    }
    await Promise.all(workers);

    if (failures.length) throw new Error(`Offline assets missing: ${failures.join(', ')}`);
    await notifyClients({ type: 'OFFLINE_READY' });
  } catch (err) {
    console.warn('Background offline preparation error:', err);
    await notifyClients({ type: 'OFFLINE_ERROR' });
  }
}

async function notifyClients(message) {
  const clients = await self.clients.matchAll();
  for (const client of clients) {
    client.postMessage(message);
  }
}

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);
  const isNavigation =
    request.mode === 'navigate' ||
    request.destination === 'document' ||
    url.pathname.endsWith('/index.html') ||
    url.pathname.endsWith('/');

  // Network-First for HTML navigation: guarantees updates are immediately delivered when server is accessible
  if (isNavigation) {
    event.respondWith(
      (async () => {
        try {
          const networkResponse = await fetch(request);
          if (networkResponse && networkResponse.status === 200) {
            const cache = await caches.open(CACHE_NAME);
            cache.put(request, networkResponse.clone()).catch(() => {});
            return networkResponse;
          }
        } catch {
          // Network failed (offline)
        }
        const cached =
          (await caches.match(request)) ||
          (await caches.match('./index.html')) ||
          (await caches.match('./'));
        if (cached) return cached;
        throw new Error('Offline and navigation document not cached');
      })(),
    );
    return;
  }

  // Cache-First for static assets, WASM, wheels, and fonts
  event.respondWith(
    (async () => {
      // 1. Try cache
      const cached = await caches.match(request);
      if (cached) {
        return cached;
      }

      // 2. Try network
      try {
        const networkResponse = await fetch(request);
        if (networkResponse && networkResponse.status === 200) {
          if (
            url.origin === self.location.origin &&
            (url.pathname.includes('/assets/') ||
              url.pathname.includes('/pyodide/') ||
              url.pathname.includes('/fonts/') ||
              url.pathname.endsWith('.png') ||
              url.pathname.endsWith('.svg') ||
              url.pathname.endsWith('.webmanifest'))
          ) {
            const cache = await caches.open(CACHE_NAME);
            cache.put(request, networkResponse.clone()).catch(() => {});
          }
        }
        return networkResponse;
      } catch (err) {
        throw err;
      }
    })(),
  );
});
